-- Vedligeholdelsesfunktion: retter auto-increment-tælleren for en tabel, hvis
-- den nogensinde kommer ud af trit med de faktiske id'er (fx efter en import
-- med eksplicitte id'er, se migrations/002_pre_real_data_import.sql). Ufarlig
-- at have liggende, selvom du aldrig får brug for den.
create or replace function reset_all_sequences()
returns void
language plpgsql
security definer
as $$
begin
  perform setval(pg_get_serial_sequence('books','id'),        coalesce((select max(id) from books), 1));
  perform setval(pg_get_serial_sequence('jumbo_books','id'),  coalesce((select max(id) from jumbo_books), 1));
  perform setval(pg_get_serial_sequence('comic_years','id'),  coalesce((select max(id) from comic_years), 1));
  perform setval(pg_get_serial_sequence('records','id'),      coalesce((select max(id) from records), 1));
  perform setval(pg_get_serial_sequence('trips','id'),        coalesce((select max(id) from trips), 1));
end;
$$;

grant execute on function reset_all_sequences() to authenticated;

-- ============================================================================
-- Row Level Security
--
-- Model: alle (også ikke-loggede-ind besøgende) kan LÆSE. Kun en logget-ind
-- bruger (Supabase Auth) kan oprette/redigere/slette. Dette er en direkte,
-- mere robust erstatning for Atlas 1's håndrullede password-gate — RLS
-- håndhæves af Postgres selv, ikke af applikationskode, og kan ikke omgås
-- ved at kalde et andet endpoint.
--
-- Supabase mapper automatisk enhver anmodning til én af to Postgres-roller:
--   - "anon"          når der ikke er noget gyldigt login (kun apikey-header)
--   - "authenticated" når der medsendes et gyldigt Supabase Auth-access-token
-- ============================================================================

alter table books enable row level security;

drop policy if exists "books_public_read" on books;
create policy "books_public_read"
  on books for select
  to anon, authenticated
  using (true);

drop policy if exists "books_authenticated_write" on books;
create policy "books_authenticated_write"
  on books for all
  to authenticated
  using (true)
  with check (true);

