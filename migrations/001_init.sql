create table if not exists books (
  id               bigint generated by default as identity primary key,
  title            text not null,
  author           text not null default '',
  year             integer,
  isbn             text,
  cover_id         bigint,
  openlibrary_key  text,
  cover_data       text,
  source           text,
  needs_review     boolean not null default false,
  verified         boolean not null default false,
  notes            text,
  rating           text,
  created_at       timestamptz not null default now(),
  updated_at       timestamptz not null default now()
);

-- updated_at skal opdateres automatisk ved enhver ændring, uanset om skrivningen
-- sker via PostgREST PATCH, SQL Editor eller andet — dette var tidligere hardkodet
-- i Node-lagets updateBook()-funktion; nu er det databasens eget ansvar, hvilket
-- er mere robust (virker uanset hvilken klient der skriver).
create or replace function set_updated_at()
returns trigger as $$
begin
  new.updated_at = now();
  return new;
end;
$$ language plpgsql;

drop trigger if exists books_set_updated_at on books;
create trigger books_set_updated_at
  before update on books
  for each row execute function set_updated_at();

